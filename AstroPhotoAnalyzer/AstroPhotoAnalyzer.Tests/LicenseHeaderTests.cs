using System.Runtime.CompilerServices;

namespace AstroPhotoAnalyzer.Tests;

/// <summary>
/// GPLv3 requires every copy to carry the notice, so every source file starts with it: the
/// SPDX line (the variant licence scanners can read), the copyright, and the three standard
/// paragraphs. This test is the only thing that keeps the convention alive when a new file
/// is added.
///
/// LICENSE is checked too: that it exists, and that it is the GPL v3 text itself, not a
/// paraphrase.
/// </summary>
public class LicenseHeaderTests
{
    static string RepoDir([CallerFilePath] string thisFile = "")
        => Path.GetDirectoryName(Path.GetDirectoryName(thisFile))!;

    /// <summary>The notice, without the comment prefix - that differs from C# to Python.</summary>
    static readonly string[] Notice =
    {
        "SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "Copyright (C) 2026 Tudor Carean",
        "",
        "This program is free software: you can redistribute it and/or modify",
        "it under the terms of the GNU General Public License as published by",
        "the Free Software Foundation, either version 3 of the License, or",
        "(at your option) any later version.",
        "",
        "This program is distributed in the hope that it will be useful,",
        "but WITHOUT ANY WARRANTY; without even the implied warranty of",
        "MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the",
        "GNU General Public License for more details.",
        "",
        "You should have received a copy of the GNU General Public License",
        "along with this program.  If not, see <https://www.gnu.org/licenses/>.",
    };

    /// <summary>
    /// The scanned projects. The list is explicit, not discovered from the solution, precisely
    /// so that adding a new project is a decision: a project forgotten here would let its
    /// files escape the notice without anything complaining. A listed project whose folder
    /// does not exist fails the scan, so that a renamed project cannot leave it unnoticed.
    /// </summary>
    static readonly string[] Projects =
    {
        "AstroPhotoAnalyzer", "AstroPhotoAnalyzer.Core", "AstroPhotoAnalyzer.Tests",
        "AstroPhotoAnalyzer.Wpf", "AstroPhotoAnalyzer.Wpf.Tests",
    };

    /// <summary>
    /// The source extensions, with the comment form that fits each. The XAML is source just
    /// like the C# - it describes the interface, it is written by hand - so it carries the
    /// notice too.
    /// </summary>
    static readonly (string Ext, string Open, string? Close)[] Kinds =
    {
        (".cs",   "//",   null),
        (".xaml", "<!--", "-->"),
        (".py",   "#",    null),
    };

    static IEnumerable<string> SourceFiles()
    {
        string root = RepoDir();

        foreach (string project in Projects)
        {
            string dir = Path.Combine(root, project);
            Assert.True(Directory.Exists(dir), $"the listed project {project} has no folder at {dir}");

            foreach (string f in Directory.EnumerateFiles(dir, "*", SearchOption.AllDirectories))
            {
                if (!Kinds.Any(k => k.Ext == Path.GetExtension(f))) continue;

                // bin/ and obj/ hold files generated by MSBuild (AssemblyInfo, the intermediate
                // XAML) - they are not our source and have no reason to carry the notice.
                string rel = Path.GetRelativePath(root, f).Replace('\\', '/');
                if (rel.Contains("/bin/") || rel.Contains("/obj/")) continue;
                yield return f;
            }
        }

        // The icon generator belongs to no project, but it is source written by hand.
        string icon = Path.Combine(root, "Icon");
        if (Directory.Exists(icon))
            foreach (string f in Directory.EnumerateFiles(icon, "*.py", SearchOption.TopDirectoryOnly))
                yield return f;
    }

    /// <summary>
    /// Renders the notice in the form the language requires. C# and Python prefix every
    /// line; XAML cannot - "&lt;!--" cannot be repeated on every line without closing the
    /// comment - so there the notice sits between an opening line and a closing one, with
    /// the text untouched between them.
    /// </summary>
    static string Expected((string Ext, string Open, string? Close) kind)
        => kind.Close == null
            ? string.Join("\n", Notice.Select(l => (kind.Open + " " + l).TrimEnd()))
            : kind.Open + "\n" + string.Join("\n", Notice) + "\n" + kind.Close;

    static (string Ext, string Open, string? Close) KindOf(string file)
        => Kinds.First(k => k.Ext == Path.GetExtension(file));

    static string HeaderOf(string file)
    {
        var kind = KindOf(file);
        string text = File.ReadAllText(file).Replace("\r\n", "\n");
        var lines = text.Split('\n').ToList();

        // The shebang of a .py must stay on the first line, so the notice comes under it.
        if (lines.Count > 0 && lines[0].StartsWith("#!")) lines.RemoveAt(0);

        // The same for the XML declaration, if there is one: it must come before the comment.
        if (lines.Count > 0 && lines[0].StartsWith("<?xml")) lines.RemoveAt(0);

        return string.Join("\n", lines.Take(Notice.Length + (kind.Close == null ? 0 : 2)));
    }

    [Fact]
    public void R121_EverySourceFileStartsWithTheLicenseNotice()
    {
        var offenders = SourceFiles()
            .Where(f => HeaderOf(f) != Expected(KindOf(f)))
            .Select(f => Path.GetRelativePath(RepoDir(), f))
            .ToList();

        Assert.True(offenders.Count == 0,
            "Files without the licence notice at the top:\n  " + string.Join("\n  ", offenders));
    }

    /// <summary>If the enumeration went wrong, the test above would pass on zero files.</summary>
    [Fact]
    public void R121_TheScanSeesEveryProjectAndTheIconScript()
    {
        var names = SourceFiles().Select(Path.GetFileName).ToList();

        Assert.Contains("Version.cs", names);              // AstroPhotoAnalyzer.Core
        Assert.Contains("AnalyzerCli.cs", names);          // AstroPhotoAnalyzer
        Assert.Contains("LicenseHeaderTests.cs", names);   // AstroPhotoAnalyzer.Tests
        Assert.Contains("make_icon.py", names);            // Icon/
        Assert.True(names.Count > 8, "too few files scanned: " + names.Count);
    }

    [Fact]
    public void R121_TheRepoShipsTheFullGplText()
    {
        string license = File.ReadAllText(Path.Combine(RepoDir(), "LICENSE"));

        Assert.Contains("GNU GENERAL PUBLIC LICENSE", license);
        Assert.Contains("Version 3, 29 June 2007", license);
        Assert.Contains("TERMS AND CONDITIONS", license);
        Assert.Contains("How to Apply These Terms to Your New Programs", license);
    }
}
